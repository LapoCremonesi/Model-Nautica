export const qs = (sel, root = document) => root.querySelector(sel);
export const qsa = (sel, root = document) => [...root.querySelectorAll(sel)];

/** Escape per interpolare testo dentro i template literal. */
export function esc(value = '') {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Spezza una stringa in <span class="word"> per animarla parola per parola. */
export function splitWords(text) {
  return String(text)
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => `<span class="w"><span>${esc(word)}</span></span>`)
    .join(' ');
}

